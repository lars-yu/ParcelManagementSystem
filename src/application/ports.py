"""Infrastructure contracts. Services depend on these protocols, not SQL/HTTP."""
from typing import Protocol, Any
from ..contracts import InboundRequest
from ..domain.models import Actor, Page


class StationRepository(Protocol):
    def register(self, request: InboundRequest, phone: str, carrier: str,
                 code_hash: str, notification: dict) -> dict: ...
    def pickup_verified(self, parcel_id: int, recipient: str, code: str, actor: str) -> dict: ...
    def get(self, parcel_id: int) -> dict: ...
    def search(self, filters: dict, page: int, page_size: int) -> Page: ...
    def export(self, filters: dict, limit: int) -> list[dict]: ...
    def mark_exception(self, parcel_id: int, kind: str, note: str, actor: str) -> dict: ...
    def resolve_exception(self, exception_id: int, resolution: str, note: str, actor: str) -> dict: ...
    def relocate(self, parcel_id: int, location: str, actor: str) -> dict: ...
    def reset_pickup(self, parcel_id: int, actor: str) -> dict: ...
    def overdue(self, cutoff: str, page: int, page_size: int) -> Page: ...
    def statistics(self, cutoff: str) -> dict: ...
    def audits(self, parcel_id: int | None, page: int, page_size: int) -> Page: ...


class IdentityRepository(Protocol):
    def create_user(self, username: str, password_hash: str, role: str) -> dict: ...
    def find_user(self, username: str) -> dict | None: ...
    def save_session(self, digest: str, username: str, expires_at: str) -> None: ...
    def find_session(self, digest: str, now: str) -> Actor | None: ...


class NotificationQueue(Protocol):
    def claim_notification(self, now: str, lease_until: str) -> dict | None: ...
    def finish_notification(self, event_id: int, claim_token: str, status: str,
                            next_attempt_at: str, error: str) -> None: ...
    def notifications(self, page: int, page_size: int) -> Page: ...


class NotificationGateway(Protocol):
    def send(self, event_key: str, payload: dict[str, Any]) -> None:
        """Use event_key as provider idempotency key; raise on failure."""


class Clock(Protocol):
    def __call__(self) -> str:
        """UTC timestamp in YYYY-MM-DDTHH:MM:SSZ format."""
